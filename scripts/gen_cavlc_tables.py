"""Generate src/cavlc_tables.rs from FFmpeg's copy of the H.264 CAVLC code tables.

The tables themselves are those of ITU-T H.264 (Tables 9-4, 9-5, 9-7, 9-8, 9-9, 9-10);
FFmpeg stores them as separate length/code arrays, which are re-emitted here as
(length, code) pairs.

usage: python scripts/gen_cavlc_tables.py <ffmpeg>/libavcodec > src/cavlc_tables.rs
"""
import os
import re
import sys


def array(src, name):
    m = re.search(r"\b" + re.escape(name) + r"\b\s*(\[[^=]*)=\s*\{(.*?)\};", src, re.S)
    if not m:
        sys.exit(f"array {name} not found")
    body = re.sub(r"/\*.*?\*/", "", m[2], flags=re.S)
    if "{" in body:
        return [[int(x) for x in re.findall(r"\d+", row)] for row in re.findall(r"\{([^{}]*)\}", body)]
    return [int(x) for x in re.findall(r"\d+", body)]


def codes(lens, bits, n=None):
    pairs = list(zip(lens, bits + [0] * (len(lens) - len(bits))))
    return pairs[:n] if n is not None else pairs


def fmt(pairs):
    return "[" + ", ".join(f"({l}, {c})" for l, c in pairs) + "]"


def main():
    d = sys.argv[1]
    cavlc = open(os.path.join(d, "h264_cavlc.c"), encoding="utf-8").read()
    data = open(os.path.join(d, "h264data.c"), encoding="utf-8").read()
    out = []
    w = out.append
    w("//! CAVLC code tables of ITU-T H.264 (Tables 9-4, 9-5, 9-7, 9-8, 9-9 and 9-10) as")
    w("//! (length, code) pairs; length 0 marks combinations without a code.")
    w("//! Generated by scripts/gen_cavlc_tables.py from FFmpeg's libavcodec/h264_cavlc.c.")
    w("")
    w("pub type Code = (u8, u16);")
    w("")
    lens, bits = array(cavlc, "coeff_token_len"), array(cavlc, "coeff_token_bits")
    w("/// coeff_token for 0 <= nC < 2, 2 <= nC < 4, 4 <= nC < 8, 8 <= nC; index total_coeff * 4 + trailing_ones")
    w("pub const COEFF_TOKEN: [[Code; 68]; 4] = [")
    for l, b in zip(lens, bits):
        w(f"    {fmt(codes(l, b))},")
    w("];")
    w("")
    w("/// coeff_token for nC == -1 (4:2:0 chroma DC); index total_coeff * 4 + trailing_ones")
    w(f"pub const COEFF_TOKEN_CHROMA_DC_420: [Code; 20] = {fmt(codes(array(cavlc, 'chroma_dc_coeff_token_len'), array(cavlc, 'chroma_dc_coeff_token_bits')))};")
    w("")
    w("/// coeff_token for nC == -2 (4:2:2 chroma DC); index total_coeff * 4 + trailing_ones")
    w(f"pub const COEFF_TOKEN_CHROMA_DC_422: [Code; 36] = {fmt(codes(array(cavlc, 'chroma422_dc_coeff_token_len'), array(cavlc, 'chroma422_dc_coeff_token_bits')))};")
    w("")

    def rows(name, prefix, count, entries):
        lens, bits = array(cavlc, prefix + "_len"), array(cavlc, prefix + "_bits")
        w(f"pub const {name}: [&[Code]; {count}] = [")
        for i in range(count):
            w(f"    &{fmt(codes(lens[i], bits[i], entries(i)))},")
        w("];")
        w("")

    w("/// total_zeros for 4x4 blocks; [total_coeff - 1][total_zeros]")
    rows("TOTAL_ZEROS_4X4", "total_zeros", 15, lambda i: 16 - i)
    w("/// total_zeros for 4:2:0 chroma DC; [total_coeff - 1][total_zeros]")
    rows("TOTAL_ZEROS_CHROMA_DC_420", "chroma_dc_total_zeros", 3, lambda i: 4 - i)
    w("/// total_zeros for 4:2:2 chroma DC; [total_coeff - 1][total_zeros]")
    rows("TOTAL_ZEROS_CHROMA_DC_422", "chroma422_dc_total_zeros", 7, lambda i: 8 - i)
    w("/// run_before; [min(zeros_left, 7) - 1][run_before]")
    rows("RUN_BEFORE", "run", 7, lambda i: i + 2 if i < 6 else 15)

    w("/// coded_block_pattern codeNum -> value (Table 9-4), ChromaArrayType 1 or 2")
    w(f"pub const CBP_INTRA: [u8; 48] = {array(data, 'ff_h264_golomb_to_intra4x4_cbp')};")
    w(f"pub const CBP_INTER: [u8; 48] = {array(data, 'ff_h264_golomb_to_inter_cbp')};")
    w("/// coded_block_pattern codeNum -> value (Table 9-4), ChromaArrayType 0 or 3")
    w(f"pub const CBP_INTRA_GRAY: [u8; 16] = {array(cavlc, 'golomb_to_intra4x4_cbp_gray')};")
    w(f"pub const CBP_INTER_GRAY: [u8; 16] = {array(cavlc, 'golomb_to_inter_cbp_gray')};")
    print("\n".join(out))


main()
